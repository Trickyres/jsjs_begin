const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../..');
const sandbox={window:{},state:{mapMode:null},BINJIANG_ROUTE_MODE:'binjiang-route'};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(root,'points-data.js'),'utf8'),sandbox);
const points=JSON.parse(JSON.stringify(sandbox.window.POINTS_DATA));
const restore=JSON.parse(fs.readFileSync(path.join(__dirname,'恢复五店位置记录.json'),'utf8'));
const before=JSON.parse(fs.readFileSync(path.join(__dirname,'update-records.json'),'utf8'));
const js=fs.readFileSync(path.join(root,'index_renew.js'),'utf8');
vm.runInContext(js.slice(js.indexOf('function getAmapMarkerOffset('),js.indexOf('function renderAmapMarkers()')),sandbox);
for(const entry of restore.restoredPoints){
  const point=points.find(p=>p.id===entry.id),previous=before.actions.find(p=>p.id===entry.id);
  assert(point&&!Object.hasOwn(point,'markerOffset'),'Display offset remains: '+entry.id);
  assert.deepEqual([point.lng,point.lat],[entry.lng,entry.lat]);
  assert.equal(point.name,previous.name);assert.equal(point.address,previous.address);assert.equal(point.image,previous.image);
  assert(fs.existsSync(path.join(root,point.image)));
  assert.equal(JSON.stringify(sandbox.getAmapMarkerOffset(point)),'[0,0]');
}
assert.equal(points.length,56);assert.equal(points.filter(p=>p.image).length,54);
assert.deepEqual(points.find(p=>p.id==='tonecoffee').markerOffset,[-8,40]);
assert(!points.some(p=>p.id==='kangyou-siji'));
assert.equal(points.find(p=>p.id==='haoxiang').image,'assets/points/haoxiang-tobacco-20261014.webp');
assert.equal(points.find(p=>p.id==='beef-noodles-lamb-soup-yangguangli').name,'牛肉面羊肉汤（阳光里店）');
const reviews={window:{}};vm.runInNewContext(fs.readFileSync(path.join(root,'point-reviews-data.js'),'utf8'),reviews);
assert.equal(Object.keys(reviews.window.POINT_REVIEWS_DATA.entries).length,8);
for(const [id,score] of [['xiaolaoban',4],['alishaokao',4],['laochengxiangtangbao',4],['traditional-beef-noodles',3]])assert.equal(reviews.window.POINT_REVIEWS_DATA.entries[id].rating,score);
for(const html of ['index.html','index_renew.html'])assert(fs.readFileSync(path.join(root,html),'utf8').includes('points-data.js?v='));
const result={localOnly:true,deployed:false,restored:restore.restoredPoints.map(e=>({id:e.id,coordinates:'unchanged',displayOffset:[0,0],nameAddressPhoto:'unchanged'})),otherChangesPreserved:true,shortReviewsPreserved:8};
fs.writeFileSync(path.join(__dirname,'five-point-restore-verification.json'),JSON.stringify(result,null,2));
console.log(JSON.stringify(result));
